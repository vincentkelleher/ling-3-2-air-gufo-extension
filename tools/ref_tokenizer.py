#!/usr/bin/env python3
"""Write fixtures/tokenizer_cases.json from the reference tokenizer.

The reference is the checkpoint's own tokenizer.json, loaded by the Rust
`tokenizers` library: `encode(text, add_special_tokens=False)`. The C++ test
`tests/tokenizer_test.cpp` must reproduce every id.

Usage:
  tools/ref_tokenizer.py [--tokenizer PATH] [--corpus PATH...] [--out PATH]

The corpus defaults to the publisher's calibration text when present, which is
plain prose rendered through this model's own chat template, plus the fixed
adversarial cases below.
"""

