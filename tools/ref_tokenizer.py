def chunks(text, size, step):
    out = []
    for start in range(0, max(1, len(text) - size), step):
        piece = text[start : start + size]
        if piece.strip():
            out.append(piece)
    return out


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--tokenizer", default=os.path.join(MODEL_DIR, "tokenizer.json"))
    parser.add_argument("--corpus", nargs="*", default=None)
    parser.add_argument("--out", default="fixtures/tokenizer_cases.json")
    parser.add_argument("--corpus-cases", type=int, default=120)
    args = parser.parse_args()

    corpus_paths = args.corpus
    if corpus_paths is None:
        default = os.path.join(MODEL_DIR, "calibration-v6.txt")
        corpus_paths = [default] if os.path.exists(default) else []

    texts = list(FIXED)
    bodies = []
    for path in corpus_paths:
        with open(path, encoding="utf-8") as handle:
            bodies.append(handle.read())
    if bodies:
        body = "\n\n".join(bodies)
        candidates = chunks(body, 320, 977)
        rng = random.Random(20261125)
        rng.shuffle(candidates)
        texts.extend(candidates[: args.corpus_cases])

    tokenizer = Tokenizer.from_file(args.tokenizer)
    cases = []
    for text in texts:
        ids = tokenizer.encode(text, add_special_tokens=False).ids
        cases.append({"text": text, "ids": ids})

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as handle:
        json.dump(
            {
                "note": "generated by tools/ref_tokenizer.py from the reference tokenizer.json",
                "tokenizer": os.path.basename(args.tokenizer),
                "cases": cases,
            },
            handle,
            ensure_ascii=False,
            indent=0,
        )
    tokens = sum(len(c["ids"]) for c in cases)
    print(f"wrote {args.out}: {len(cases)} cases, {tokens} tokens")


if __name__ == "__main__":
    main()
