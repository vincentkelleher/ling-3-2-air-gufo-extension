#!/usr/bin/env python3
"""Generate src/text/unicode_tables.cpp for the Ling 3.2 pre-tokenizer.

The pre-tokenizer regex only distinguishes Unicode letters (\\p{L}), numbers
(\\p{N}) and white space (\\s, the Unicode White_Space property), so the table
keeps exactly those classes instead of every general category.

Usage: python3 tools/gen_unicode_tables.py > src/text/unicode_tables.cpp
"""

import sys
import unicodedata

# Unicode White_Space property (PropList.txt). Python's str.isspace() also
# counts U+001C..U+001F, which are not White_Space.
WHITE_SPACE = (
    list(range(0x09, 0x0E))
    + [0x20, 0x85, 0xA0, 0x1680]
    + list(range(0x2000, 0x200B))
    + [0x2028, 0x2029, 0x202F, 0x205F, 0x3000]
)

K_LETTER = 1
K_NUMBER = 2
K_SPACE = 0x80


def classify(cp: int) -> int:
    if cp in WHITE_SPACE:
        return K_SPACE
    category = unicodedata.category(chr(cp))
    if category.startswith("L"):
        return K_LETTER
    if category.startswith("N"):
        return K_NUMBER
    return 0


def ranges():
    start = None
    code = 0
    for cp in range(0x110000):
        c = classify(cp)
        if c == code and start is not None:
            continue
        if start is not None and code != 0:
            yield start, cp - 1, code
        start = cp if c != 0 else None
        code = c
    if start is not None and code != 0:
        yield start, 0x10FFFF, code


def main() -> None:
    out = sys.stdout
    out.write(
        "// Generated by tools/gen_unicode_tables.py from Python %s (Unicode %s).\n"
        "// Do not edit.\n"
        '#include "src/text/unicode.hpp"\n\n'
        "namespace gufo::ext::ling3_air::text::unicode {\n\n"
        "const CodepointRange kRanges[] = {\n"
        % (sys.version.split()[0], unicodedata.unidata_version)
    )
    line = []
    for first, last, code in ranges():
        line.append("{0x%X,0x%X,%d}," % (first, last, code))
        if len(line) == 6:
            out.write("".join(line) + "\n")
            line = []
    if line:
        out.write("".join(line) + "\n")
    out.write("};\nconst std::size_t kRangeCount = sizeof(kRanges) / sizeof(kRanges[0]);\n")
    out.write("\n}  // namespace gufo::ext::ling3_air::text::unicode\n")


if __name__ == "__main__":
    main()
